"""Deterministic stub agent: rule-based planning/validation/reporting without LLM."""
from core.findings import Finding
from core.memory import log_event, scan_dir
from core.cvss import score, vector

VALIDATION_RULES = {
    "xss": {"min_confidence": 0.6, "requires": ["payload", "evidence"], "severity_floor": "medium"},
    "sqli": {"min_confidence": 0.7, "requires": ["payload", "evidence"], "severity_floor": "high"},
    "ssrf": {"min_confidence": 0.6, "requires": ["payload", "evidence"], "severity_floor": "high"},
    "rce": {"min_confidence": 0.8, "requires": ["payload", "evidence"], "severity_floor": "critical"},
    "lfi": {"min_confidence": 0.7, "requires": ["payload", "evidence"], "severity_floor": "high"},
    "idor": {"min_confidence": 0.5, "requires": ["payload"], "severity_floor": "medium"},
    "default": {"min_confidence": 0.5, "requires": ["evidence"], "severity_floor": "low"},
}

def classify(finding):
    t = finding.type.lower()
    for key in VALIDATION_RULES:
        if key in t:
            return VALIDATION_RULES[key]
    return VALIDATION_RULES["default"]

def validate(finding):
    rule = classify(finding)
    if finding.confidence < rule["min_confidence"]:
        return False, "Confidence {} < {}".format(finding.confidence, rule["min_confidence"])
    for req in rule["requires"]:
        if not getattr(finding, req, None):
            return False, "Missing required field: {}".format(req)
    sev_rank = {"critical": 4, "high": 3, "medium": 2, "low": 1, "info": 0}
    if sev_rank.get(finding.severity, 0) < sev_rank.get(rule["severity_floor"], 0):
        finding.severity = rule["severity_floor"]
    finding.verified = True
    return True, "passed deterministic validation"

def plan(findings):
    sev_rank = {"critical": 4, "high": 3, "medium": 2, "low": 1, "info": 0}
    sorted_f = sorted(findings, key=lambda f: (sev_rank.get(f.severity, 0), f.confidence), reverse=True)
    plan_lines = ["Deterministic plan (no LLM):"]
    for i, f in enumerate(sorted_f[:15]):
        plan_lines.append("{}. [{}] {} @ {} (conf: {})".format(i+1, f.severity.upper(), f.type, f.url, f.confidence))
    types = [f.type.lower() for f in findings]
    if any("xss" in t for t in types) and any("csrf" in t or "session" in t for t in types):
        plan_lines.append("CHAIN: XSS + Session issue -> Account takeover")
    if any("sqli" in t for t in types):
        plan_lines.append("CHAIN: SQLi -> Data exfiltration -> Privilege escalation")
    if any("ssrf" in t for t in types):
        plan_lines.append("CHAIN: SSRF -> Cloud metadata -> Credential theft")
    if any("lfi" in t for t in types) or any("traversal" in t for t in types):
        plan_lines.append("CHAIN: LFI -> Source code disclosure -> Credential leak")
    if any("idor" in t for t in types):
        plan_lines.append("CHAIN: IDOR -> Mass data exfiltration")
    return "\n".join(plan_lines)

def generate_report(findings, target, domain):
    lines = []
    lines.append("# Bug Bounty Report — {}".format(domain))
    lines.append("Generated by Deterministic Stub (no LLM)")
    lines.append("")
    lines.append("## Summary")
    lines.append("Total validated findings: {}".format(len(findings)))
    lines.append("")
    by_sev = {}
    for f in findings:
        by_sev.setdefault(f.severity, []).append(f)
    for sev in ["critical", "high", "medium", "low"]:
        if sev in by_sev:
            lines.append("### {} ({})".format(sev.upper(), len(by_sev[sev])))
            for f in by_sev[sev]:
                lines.append("- **{}** — {}".format(f.type, f.url))
                lines.append("  - Param: `{}`".format(f.parameter))
                lines.append("  - Payload: `{}`".format(f.payload))
                lines.append("  - Evidence: {}".format(f.evidence))
                lines.append("  - CVSS: {} ({})".format(score(f), vector(f)))
                lines.append("  - Confidence: {}".format(f.confidence))
            lines.append("")
    lines.append("## Findings Detail")
    for i, f in enumerate(findings, 1):
        lines.append("### Finding {}: {}".format(i, f.type))
        lines.append("- **Severity:** {}".format(f.severity))
        lines.append("- **URL:** {}".format(f.url))
        lines.append("- **Parameter:** {}".format(f.parameter))
        lines.append("- **Payload:** `{}`".format(f.payload))
        lines.append("- **Evidence:** {}".format(f.evidence))
        lines.append("- **CVSS:** {} ({})".format(score(f), vector(f)))
        lines.append("- **Response snippet:**")
        lines.append("```")
        lines.append((f.response_snippet or "")[:500])
        lines.append("```")
        lines.append("")
    return "\n".join(lines)

def seven_question_gate(finding):
    questions = [
        "Can an attacker exploit this right now?",
        "Is the impact concrete and in-scope?",
        "Is the evidence reproducible?",
        "Is this not a duplicate?",
        "Does it bypass existing controls?",
        "Is the asset in scope?",
        "Would a triager accept this?",
    ]
    score_val = 0
    if finding.verified:
        score_val += 2
    if finding.confidence >= 0.7:
        score_val += 2
    if finding.severity in ("critical", "high"):
        score_val += 1
    if finding.evidence and len(finding.evidence) > 20:
        score_val += 1
    if finding.payload:
        score_val += 1
    passed = score_val >= 4
    return {q: passed for q in questions}, score_val
